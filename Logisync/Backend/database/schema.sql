-- SYNCLINK DATABASE
-- PostgreSQL / Neon

-- 1. USERS
CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('seller', 'coordinator', 'rider')),
    verification_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED'
        CHECK (verification_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. PARCELS
CREATE TABLE IF NOT EXISTS parcels (
    parcel_id VARCHAR(50) PRIMARY KEY,
    seller_id INTEGER NOT NULL,
    receiver_name VARCHAR(100) NOT NULL,
    receiver_contact VARCHAR(50),
    contents VARCHAR(255),
    transaction_number VARCHAR(100) UNIQUE,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN (
            'PENDING',
            'WAITING_FOR_VIDEO',
            'VIDEO_SUBMITTED',
            'VERIFIED',
            'REJECTED',
            'REUPLOAD_REQUESTED'
        )),
    verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (verification_status IN (
            'PENDING',
            'VERIFIED',
            'REJECTED',
            'REUPLOAD_REQUESTED'
        )),
    rider_id INTEGER,
    delivery_status VARCHAR(20)
        CHECK (delivery_status IN ('TO_DELIVER', 'DELIVERED', 'FAILED')),
    delivery_note VARCHAR(500),
    scanned_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_parcel_seller
        FOREIGN KEY (seller_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_parcel_rider
        FOREIGN KEY (rider_id)
        REFERENCES users(user_id)
        ON DELETE SET NULL
        ON UPDATE CASCADE
);

-- 3. VIDEO PROOFS
CREATE TABLE IF NOT EXISTS video_proofs (
    video_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id VARCHAR(50) NOT NULL,
    uploaded_by INTEGER NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    file_size BIGINT NOT NULL,
    mime_type VARCHAR(100) NOT NULL,
    uploaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_video_parcel
        FOREIGN KEY (parcel_id)
        REFERENCES parcels(parcel_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_video_user
        FOREIGN KEY (uploaded_by)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- 4. VERIFICATION RECORDS
CREATE TABLE IF NOT EXISTS verification_records (
    verification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcel_id VARCHAR(50) NOT NULL,
    coordinator_id INTEGER NOT NULL,
    decision VARCHAR(30) NOT NULL
        CHECK (decision IN (
            'VERIFY',
            'REJECT',
            'REQUEST_REUPLOAD'
        )),
    remarks TEXT,
    verified_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_verification_parcel
        FOREIGN KEY (parcel_id)
        REFERENCES parcels(parcel_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT fk_verification_coordinator
        FOREIGN KEY (coordinator_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- 5. COMMUNICATION MESSAGES
CREATE TABLE IF NOT EXISTS communication_messages (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id INTEGER NOT NULL,
    receiver_id INTEGER NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_message_sender
        FOREIGN KEY (sender_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT fk_message_receiver
        FOREIGN KEY (receiver_id)
        REFERENCES users(user_id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- 6. AUDIT LOGS
CREATE TABLE IF NOT EXISTS audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER,
    actor_name VARCHAR(100) NOT NULL,
    actor_role VARCHAR(20) NOT NULL,
    category VARCHAR(40) NOT NULL,
    action VARCHAR(100) NOT NULL,
    target VARCHAR(100),
    detail VARCHAR(500),
    seller_id INTEGER,
    rider_id INTEGER,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_logs(actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_seller ON audit_logs(seller_id);
CREATE INDEX IF NOT EXISTS idx_audit_rider ON audit_logs(rider_id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(created_at);

-- AUTOMATIC updated_at FUNCTION
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- USERS TRIGGER
DROP TRIGGER IF EXISTS users_updated_at_trigger ON users;

CREATE TRIGGER users_updated_at_trigger
BEFORE UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION update_updated_at();

-- PARCELS TRIGGER
DROP TRIGGER IF EXISTS parcels_updated_at_trigger ON parcels;

CREATE TRIGGER parcels_updated_at_trigger
BEFORE UPDATE ON parcels
FOR EACH ROW
EXECUTE FUNCTION update_updated_at();
