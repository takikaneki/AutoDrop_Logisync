const CURRENT_POLICY_VERSION = "2026.1";
const ALLOWED_OTP_PURPOSES = new Set(["FORGOT_PASSWORD", "FIRST_LOGIN"]);
let policySchemaReady = false;

function getJwtSecret() {
  const secret = process.env.JWT_SECRET;
  if (typeof secret !== "string" || !secret.trim()) {
    const err = new Error("JWT_SECRET environment variable is not configured.");
    err.code = "MISSING_JWT_SECRET";
    throw err;
  }
  return secret;
}

async function ensurePolicySchema() {
  if (policySchemaReady) return;
  await rawPool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS privacy_accepted BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS policy_version VARCHAR(50);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS phone VARCHAR(50);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar TEXT;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS rider_code VARCHAR(20);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS agency VARCHAR(150);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS rider_type VARCHAR(2);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS first_login BOOLEAN NOT NULL DEFAULT FALSE;

    CREATE TABLE IF NOT EXISTS user_policy_acceptances (
      acceptance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
      user_role VARCHAR(20) NOT NULL,
      terms_accepted BOOLEAN NOT NULL DEFAULT TRUE,
      privacy_accepted BOOLEAN NOT NULL DEFAULT TRUE,
      policy_version VARCHAR(50) NOT NULL,
      accepted_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_policy_acceptances_user ON user_policy_acceptances(user_id);
  `);
  policySchemaReady = true;
}

function createToken(user) {
  return jwt.sign(
    {
      token_type: "session",
      user_id: user.user_id,
      name: user.name,
      email: user.email,
      role: user.role,
      session_version: Number(user.session_version || 1),
      policy_version: user.policy_version || CURRENT_POLICY_VERSION,
      terms_accepted: Boolean(user.terms_accepted),
    },
    getJwtSecret(),
    { expiresIn: "8h" }
  );
}

async function register(req, res) {
  try {
    await ensurePolicySchema();
    const { name, email, password, termsAccepted, policyVersion } = req.body;

    if (
      typeof name !== "string" ||
      !name.trim() ||
      typeof email !== "string" ||
      !email.trim() ||
      typeof password !== "string" ||
      !password
    ) {
      return res.status(400).json({
        success: false,
        message: "Name, email, and password are required.",
      });
    }

    if (password.length < 6) {
      return res.status(400).json({
        success: false,
        message: "Password must be at least 6 characters.",
      });
    }

    const cleanName = name.trim();
    const cleanEmail = email.trim().toLowerCase();

    const [existing] = await pool.query(
      "SELECT user_id FROM users WHERE email = ?",
      [cleanEmail]
    );

    if (existing.length > 0) {
      return res.status(409).json({
        success: false,
        message: "Email is already registered.",
      });
    }

    const passwordHash = await bcrypt.hash(password, 10);
    const role = "seller";
    const accepted = Boolean(termsAccepted);

    const appliedVersion =
      typeof policyVersion === "string" && policyVersion.trim()
        ? policyVersion.trim().slice(0, 50)
        : CURRENT_POLICY_VERSION;

    const [result] = await pool.query(
      `INSERT INTO users
       (name, email, password_hash, role, verification_status, terms_accepted, privacy_accepted, policy_version, terms_accepted_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, CASE WHEN ? THEN CURRENT_TIMESTAMP ELSE NULL END)`,
      [
        cleanName,
        cleanEmail,
        passwordHash,
        role,
        "PENDING",
        accepted,
        accepted,
        accepted ? appliedVersion : null,
        accepted,
      ]
    );

    if (accepted && result.insertId) {
      await pool.query(
        `INSERT INTO user_policy_acceptances
         (user_id, user_role, terms_accepted, privacy_accepted, policy_version)
         VALUES (?, ?, TRUE, TRUE, ?)`,
        [result.insertId, role, appliedVersion]
      );
    }

    const user = {
      user_id: result.insertId,
      name: cleanName,
      email: cleanEmail,
      role,
    };

    return res.status(201).json({
      success: true,
      message: "Registration successful. Your account is pending Coordinator approval.",
      user: {
        user_id: user.user_id,
        name: user.name,
        email: user.email,
        role: user.role,
        verification_status: "PENDING",
        terms_accepted: accepted,
        privacy_accepted: accepted,
        policy_version: accepted ? appliedVersion : null,
      },
    });
  } catch (error) {
    console.error("Registration error:", error);

    return res.status(500).json({
      success: false,
      message: "Registration failed.",
    });
  }
}

async function login(req, res) {
  try {
    await ensurePolicySchema();
    await ensureAccountLifecycleSchema();
    const { email, password, username, termsAccepted, policyVersion } = req.body;

    const identifier = String(email || username || req.body?.identifier || "").trim();
    if (!identifier || !password) {
      return res
        .status(400)
        .json({ success: false, message: "Email or username and password are required." });
    }

    if (!termsAccepted) {
      return res.status(400).json({
        success: false,
        message:
          "You must agree to the Terms and Conditions and Privacy Policy before signing in.",
      });
    }

    const [rows] = await pool.query(
      `SELECT user_id, name, email, phone, avatar, password_hash, role, verification_status,
              first_login, is_deleted, deactivated_at, recovery_expires_at, session_version
       FROM users
       WHERE is_deleted = FALSE
         AND (LOWER(BTRIM(email)) = LOWER(BTRIM(?))
          OR LOWER(BTRIM(name)) = LOWER(BTRIM(?)))
       LIMIT 1`,
      [identifier, identifier]
    );

    if (!rows.length) {
      return res
        .status(401)
        .json({ success: false, message: "Invalid email or password." });
    }

    const user = rows[0];
    if (Boolean(user.is_deleted)) {
      return res
        .status(401)
        .json({ success: false, message: "Invalid email or password." });
    }

    const valid = await bcrypt.compare(password, user.password_hash);

    if (!valid) {
      return res
        .status(401)
        .json({ success: false, message: "Invalid email or password." });
    }

    // AUTOMATIC ROLE DETECTION:
    // Determine the user's registered role directly from the authenticated database record.
    // Never trust or require a client-submitted role value.
    const VALID_ROLES = ["seller", "rider", "coordinator"];
    const actualRole = String(user.role || "").trim().toLowerCase();

    if (!actualRole || !VALID_ROLES.includes(actualRole)) {
      return res.status(403).json({
        success: false,
        message: "Your account does not have an authorized role. Please contact support."
      });
    }

    // Inactive / suspended / pending checks
    const verificationStatus = String(user.verification_status || "").toUpperCase();
    if (verificationStatus === "REJECTED" || user.deactivated_at != null) {
      if (
        (actualRole === "seller" || actualRole === "rider") &&
        user.recovery_expires_at &&
        new Date(user.recovery_expires_at).getTime() <= Date.now()
      ) {
        await purgeExpiredDeactivatedAccounts({ userId: user.user_id }).catch(() => {});
        return res.status(401).json({
          success: false,
          code: "ACCOUNT_DELETED",
          message: "Invalid email or password.",
        });
      }
      return res.status(403).json({
        success: false,
        code: "ACCOUNT_DEACTIVATED",
        message: "Your account has been deactivated. Please contact the Coordinator.",
      });
    }

    if (verificationStatus === "PENDING" && (actualRole === "seller" || actualRole === "rider")) {
      return res.status(403).json({
        success: false,
        message: "Your account is pending Coordinator approval.",
      });
    }

    // Check for first login requiring password change
    if (Boolean(user.first_login)) {
      const firstLoginToken = jwt.sign(
        {
          token_type: "first_login",
          user_id: user.user_id,
          email: user.email,
          purpose: "FIRST_LOGIN",
        },
        getJwtSecret(),
        { expiresIn: "15m" }
      );

      return res.json({
        success: true,
        requireFirstLoginPasswordChange: true,
        firstLoginToken,
        email: user.email,
        name: user.name,
        role: actualRole,
        message: "First-time login detected. Please change your password to continue.",
      });
    }

    const appliedVersion =
      typeof policyVersion === "string" && policyVersion.trim()
        ? policyVersion.trim().slice(0, 50)
        : CURRENT_POLICY_VERSION;

    // Save the user's agreement status, policy version, and acceptance timestamp in the database
    const [updatedRows] = await pool.query(
      `UPDATE users
       SET terms_accepted = TRUE,
           privacy_accepted = TRUE,
           policy_version = ?,
           terms_accepted_at = CURRENT_TIMESTAMP
       WHERE user_id = ?
       RETURNING terms_accepted_at`,
      [appliedVersion, user.user_id]
    );

    const acceptedAt =
      updatedRows?.[0]?.terms_accepted_at || new Date().toISOString();

    await pool.query(
      `INSERT INTO user_policy_acceptances
       (user_id, user_role, terms_accepted, privacy_accepted, policy_version, accepted_at)
       VALUES (?, ?, TRUE, TRUE, ?, CURRENT_TIMESTAMP)`,
      [user.user_id, actualRole, appliedVersion]
    );

    // Record acceptance in system audit logs for compliance traceability
    try {
      await pool.query(
        `INSERT INTO audit_logs
         (actor_id, actor_name, actor_role, category, action, target, detail)
         VALUES (?, ?, ?, 'Auth', 'Accepted Terms & Privacy Policy', ?, ?)`,
        [
          user.user_id,
          user.name,
          actualRole,
          user.email,
          `Accepted Terms and Conditions & Privacy Policy (${appliedVersion}) upon sign-in.`,
        ]
      );
    } catch {
      /* non-fatal if audit_logs insert fails */
    }

    // Rider classification (FM / LM) para sa role-based access sa frontend.
    let riderInfo = {};
    if (actualRole === "rider") {
      try {
        const [rr] = await pool.query(
          "SELECT rider_type, rider_code, agency FROM users WHERE user_id = ?",
          [user.user_id]
        );
        riderInfo = {
          rider_type: rr[0]?.rider_type || "LM",
          rider_code: rr[0]?.rider_code || null,
          agency: rr[0]?.agency || null,
        };
      } catch {
        riderInfo = { rider_type: "LM" };
      }
    }

    const home = actualRole === "seller" ? "/seller" : actualRole === "rider" ? "/rider" : "/dashboard";

    const safeUser = {
      user_id: user.user_id,
      name: user.name,
      email: user.email,
      phone: user.phone || null,
      avatar: user.avatar || null,
      role: actualRole,
      ...riderInfo,
      terms_accepted: true,
      privacy_accepted: true,
      policy_version: appliedVersion,
      terms_accepted_at: acceptedAt,
    };

    res.json({
      success: true,
      message: "Login successful.",
      token: createToken({
        ...safeUser,
        session_version: Number(user.session_version || 1),
      }),
      user: safeUser,
      redirectUrl: home,
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ success: false, message: "Login failed." });
  }
}

