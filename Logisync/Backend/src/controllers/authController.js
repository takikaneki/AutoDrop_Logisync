let otpTableReady = false;
async function ensureOtpSchema() {
  if (otpTableReady) return;
  await rawPool.query(`
    CREATE TABLE IF NOT EXISTS email_otps (
      otp_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
      email VARCHAR(150) NOT NULL,
      otp_hash VARCHAR(255) NOT NULL,
      salt VARCHAR(64) NOT NULL,
      purpose VARCHAR(50) NOT NULL,
      expires_at TIMESTAMPTZ NOT NULL,
      attempts INTEGER NOT NULL DEFAULT 0,
      max_attempts INTEGER NOT NULL DEFAULT 5,
      verified_at TIMESTAMPTZ,
      used_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_email_otps_user_purpose ON email_otps(user_id, purpose, created_at DESC);
    CREATE INDEX IF NOT EXISTS idx_email_otps_email_purpose ON email_otps(email, purpose, created_at DESC);
    CREATE INDEX IF NOT EXISTS idx_email_otps_active ON email_otps(user_id, purpose) WHERE used_at IS NULL;

    CREATE TABLE IF NOT EXISTS otp_rate_limits (
      rate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      scope_key VARCHAR(200) NOT NULL,
      action VARCHAR(50) NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_otp_rate_limits_lookup ON otp_rate_limits(scope_key, action, created_at DESC);
  `);
  otpTableReady = true;
}

function getClientIp(req) {
  const behindTrustedProxy =
    Boolean(process.env.VERCEL) ||
    process.env.TRUST_PROXY === "true" ||
    Boolean(req.app?.get?.("trust proxy"));

  if (behindTrustedProxy) {
    const vercelIp = req.headers?.["x-vercel-forwarded-for"];
    if (typeof vercelIp === "string" && vercelIp.trim()) {
      return vercelIp.split(",")[0].trim().slice(0, 64);
    }
    const xff = req.headers?.["x-forwarded-for"];
    if (typeof xff === "string" && xff.trim()) {
      return xff.split(",")[0].trim().slice(0, 64);
    }
  }

  return String(req.socket?.remoteAddress || req.ip || "unknown").slice(0, 64);
}

/**
 * Serverless-safe PostgreSQL sliding-window rate limiter using advisory locks.
 * Also prunes expired rows older than 24 hours for the locked scope/action.
 * Must be called inside a transaction on `client`.
 */
async function checkAndRecordRateLimit(client, { scopeKey, action, windowSeconds, maxRequests }) {
  await client.query("SELECT pg_advisory_xact_lock(hashtext($1))", [`rl:${action}:${scopeKey}`]);

  await client.query(
    `DELETE FROM otp_rate_limits
     WHERE scope_key = $1
       AND action = $2
       AND created_at < CURRENT_TIMESTAMP - INTERVAL '24 hours'`,
    [scopeKey, action]
  );

  const { rows } = await client.query(
    `SELECT created_at
     FROM otp_rate_limits
     WHERE scope_key = $1
       AND action = $2
       AND created_at > CURRENT_TIMESTAMP - ($3 * INTERVAL '1 second')
     ORDER BY created_at ASC`,
    [scopeKey, action, windowSeconds]
  );

  if (rows.length >= maxRequests) {
    const oldestTime = new Date(rows[0].created_at).getTime();
    const remainingSeconds = Math.max(
      1,
      Math.ceil((oldestTime + windowSeconds * 1000 - Date.now()) / 1000)
    );
    return { allowed: false, remainingSeconds, rateId: null };
  }

  const { rows: inserted } = await client.query(
    `INSERT INTO otp_rate_limits (scope_key, action)
     VALUES ($1, $2)
     RETURNING rate_id`,
    [scopeKey, action]
  );

  return { allowed: true, remainingSeconds: 0, rateId: inserted[0]?.rate_id ?? null };
}

/**
 * Concurrency-safe cleanup when OTP email delivery fails:
 * - Invalidates the undelivered OTP so it cannot be used.
 * - Releases ONLY the specific 60-second OTP_COOLDOWN record created for this attempt,
 *   preserving IP and hourly rate-limit protections.
 */
async function cleanupFailedOtpDelivery({ otpId, cooldownRateId }) {
  if (!otpId && !cooldownRateId) return;
  const client = await rawPool.connect();
  try {
    await client.query("BEGIN");
    if (otpId) {
      await client.query(
        "UPDATE email_otps SET used_at = CURRENT_TIMESTAMP WHERE otp_id = $1 AND used_at IS NULL",
        [otpId]
      );
    }
    if (cooldownRateId) {
      await client.query(
        "DELETE FROM otp_rate_limits WHERE rate_id = $1 AND action = 'OTP_COOLDOWN'",
        [cooldownRateId]
      );
    }
    await client.query("COMMIT");
  } catch (err) {
    try {
      await client.query("ROLLBACK");
    } catch (_) {}
    console.error("[OTP] Failed to clean up undelivered OTP state:", err?.code || err?.message);
  } finally {
    client.release();
  }
}

async function checkIpRateLimit(req, action, windowSeconds, maxRequests) {
  const ip = getClientIp(req);
  const client = await rawPool.connect();
  try {
    await client.query("BEGIN");
    const result = await checkAndRecordRateLimit(client, {
      scopeKey: `ip:${ip}`,
      action,
      windowSeconds,
      maxRequests,
    });
    await client.query("COMMIT");
    return result;
  } catch (err) {
    try {
      await client.query("ROLLBACK");
    } catch (_) {}
    throw err;
  } finally {
    client.release();
  }
}

/**
 * POST /api/auth/otp/request
 * POST /api/auth/otp/resend
 * Request a 6-digit OTP for FORGOT_PASSWORD or FIRST_LOGIN
 */
async function requestOtp(req, res) {
  try {
    await ensurePolicySchema();
    await ensureOtpSchema();

    // Fail safely if required server secrets are not configured
    try {
      getOtpHmacSecret();
      getJwtSecret();
    } catch (cfgErr) {
      console.error("[OTP Config Error]", cfgErr.code || cfgErr.message);
      return res.status(500).json({
        success: false,
        message: "OTP verification service is not configured on the server.",
      });
    }

    const { email, purpose = "FORGOT_PASSWORD", firstLoginToken } = req.body || {};
    const cleanPurpose = String(purpose || "").trim().toUpperCase();

    if (!ALLOWED_OTP_PURPOSES.has(cleanPurpose)) {
      return res.status(400).json({
        success: false,
        message: "Invalid OTP verification purpose.",
      });
    }

    // Server-side IP rate limit across /otp/request and /otp/resend (15 req / 15 min)
    const ipLimit = await checkIpRateLimit(req, "OTP_REQUEST", 900, 15);
    if (!ipLimit.allowed) {
      return res.status(429).json({
        success: false,
        message: `Too many OTP requests. Please wait ${ipLimit.remainingSeconds} second${ipLimit.remainingSeconds === 1 ? "" : "s"} and try again.`,
        remainingSeconds: ipLimit.remainingSeconds,
      });
    }

    // =========================================================================
    // FIRST_LOGIN FLOW (requires valid firstLoginToken)
    // =========================================================================
    if (cleanPurpose === "FIRST_LOGIN") {
      if (!firstLoginToken) {
        return res.status(401).json({
          success: false,
          message: "First-login verification token is required.",
        });
      }

      let decoded;
      try {
        decoded = jwt.verify(firstLoginToken, getJwtSecret());
      } catch {
        return res.status(401).json({
          success: false,
          message: "First-login session expired or invalid. Please sign in again.",
        });
      }

      if (
        decoded.token_type !== "first_login" ||
        decoded.purpose !== "FIRST_LOGIN" ||
        !decoded.user_id
      ) {
        return res.status(401).json({
          success: false,
          message: "Invalid first-login token.",
        });
      }

      let createdOtpId = null;
      let cooldownRateId = null;
      let otpCode = null;
      let targetUser = null;

      const client = await rawPool.connect();
      try {
        await client.query("BEGIN");

        const { rows: uRows } = await client.query(
          `SELECT user_id, name, email, role, verification_status, first_login
           FROM users
           WHERE user_id = $1
           FOR UPDATE`,
          [decoded.user_id]
        );

        if (!uRows.length) {
          await client.query("ROLLBACK");
          return res.status(404).json({
            success: false,
            message: "User account not found.",
          });
        }

        targetUser = uRows[0];
        const role = String(targetUser.role || "").toLowerCase();
        const verificationStatus = String(targetUser.verification_status || "").toUpperCase();

        if (verificationStatus === "REJECTED") {
          await client.query("ROLLBACK");
          return res.status(403).json({
            success: false,
            message: "Your account is inactive or disabled. Please contact the Coordinator.",
          });
        }

        if (verificationStatus === "PENDING" && (role === "seller" || role === "rider")) {
          await client.query("ROLLBACK");
          return res.status(403).json({
            success: false,
            message: "Your account is pending Coordinator approval.",
          });
        }

        if (!Boolean(targetUser.first_login)) {
          await client.query("ROLLBACK");
          return res.status(400).json({
            success: false,
            message: "This account has already completed first-time password setup.",
          });
        }

        // 60-second cooldown & 5/hour cap per account (concurrency-safe under user row lock)
        const cooldownCheck = await checkAndRecordRateLimit(client, {
          scopeKey: `user:${targetUser.user_id}:FIRST_LOGIN`,
          action: "OTP_COOLDOWN",
          windowSeconds: 60,
          maxRequests: 1,
        });
        if (!cooldownCheck.allowed) {
          await client.query("ROLLBACK");
          return res.status(429).json({
            success: false,
            message: `Please wait ${cooldownCheck.remainingSeconds} second${cooldownCheck.remainingSeconds === 1 ? "" : "s"} before requesting another code.`,
            remainingSeconds: cooldownCheck.remainingSeconds,
          });
        }
        cooldownRateId = cooldownCheck.rateId;

        const hourlyCheck = await checkAndRecordRateLimit(client, {
          scopeKey: `user:${targetUser.user_id}:FIRST_LOGIN`,
          action: "OTP_HOURLY",
          windowSeconds: 3600,
          maxRequests: 5,
        });
        if (!hourlyCheck.allowed) {
          await client.query("ROLLBACK");
          return res.status(429).json({
            success: false,
            message: "Too many verification codes requested. Please try again later.",
            remainingSeconds: hourlyCheck.remainingSeconds,
          });
        }

        // Invalidate any previous active FIRST_LOGIN OTPs
        await client.query(
          `UPDATE email_otps
           SET used_at = CURRENT_TIMESTAMP
           WHERE user_id = $1 AND purpose = 'FIRST_LOGIN' AND used_at IS NULL`,
          [targetUser.user_id]
        );

        otpCode = generateOtp();
        const salt = crypto.randomBytes(16).toString("hex");
        const otpHash = hashOtp(otpCode, salt, targetUser.user_id, "FIRST_LOGIN");
        const expiresAt = new Date(Date.now() + 5 * 60 * 1000);

        const { rows: inserted } = await client.query(
          `INSERT INTO email_otps
           (user_id, email, otp_hash, salt, purpose, expires_at, attempts, max_attempts)
           VALUES ($1, $2, $3, $4, 'FIRST_LOGIN', $5, 0, 5)
           RETURNING otp_id`,
          [targetUser.user_id, targetUser.email, otpHash, salt, expiresAt]
        );
        createdOtpId = inserted[0].otp_id;

        await client.query("COMMIT");
      } catch (txErr) {
        try {
          await client.query("ROLLBACK");
        } catch (_) {}
        throw txErr;
      } finally {
        client.release();
      }

      const mailRes = await sendOtpEmail({
        to: targetUser.email,
        name: targetUser.name,
        otp: otpCode,
        purpose: "FIRST_LOGIN",
      });

      if (!mailRes?.sent) {
        // Invalidate undelivered OTP and release only the 60s cooldown record
        await cleanupFailedOtpDelivery({ otpId: createdOtpId, cooldownRateId });
        return res.status(503).json({
          success: false,
          message: "Unable to send the verification email right now. Please try again shortly.",
        });
      }

      try {
        await rawPool.query(
          `INSERT INTO audit_logs
           (actor_id, actor_name, actor_role, category, action, target, detail)
           VALUES ($1, $2, $3, 'Auth', 'Requested OTP code', $4, $5)`,
          [
            targetUser.user_id,
            targetUser.name,
            targetUser.role,
            targetUser.email,
            "Generated OTP for FIRST_LOGIN.",
          ]
        );
      } catch {
        /* non-fatal */
      }

      return res.json({
        success: true,
        message: "An OTP verification code has been sent to your email address.",
        cooldownSeconds: 60,
      });
    }

    // =========================================================================
    // FORGOT_PASSWORD FLOW (public, enumeration-resistant)
    // =========================================================================
    if (!email || typeof email !== "string" || !email.trim()) {
      return res.status(400).json({
        success: false,
        message: "Please enter your registered email address.",
      });
    }

    const targetEmail = email.trim().toLowerCase();
    if (!/^\S+@\S+\.\S+$/.test(targetEmail)) {
      return res.status(400).json({
        success: false,
        message: "Please enter a valid email address.",
      });
    }

    const genericResponse = {
      success: true,
      message: "If an account with that email exists, an OTP verification code has been sent.",
      cooldownSeconds: 60,
    };

    let createdOtpId = null;
    let cooldownRateId = null;
    let otpCode = null;
    let targetUser = null;

    const client = await rawPool.connect();
    try {
      await client.query("BEGIN");

      // Enforce per-email 60s cooldown & hourly limit BEFORE checking if email exists
      // so registered and unregistered emails return identical responses & status codes.
      const cooldownCheck = await checkAndRecordRateLimit(client, {
        scopeKey: `email:${targetEmail}:FORGOT_PASSWORD`,
        action: "OTP_COOLDOWN",
        windowSeconds: 60,
        maxRequests: 1,
      });
      if (!cooldownCheck.allowed) {
        await client.query("ROLLBACK");
        return res.status(429).json({
          success: false,
          message: `Please wait ${cooldownCheck.remainingSeconds} second${cooldownCheck.remainingSeconds === 1 ? "" : "s"} before requesting another code.`,
          remainingSeconds: cooldownCheck.remainingSeconds,
        });
      }
      cooldownRateId = cooldownCheck.rateId;

      const hourlyCheck = await checkAndRecordRateLimit(client, {
        scopeKey: `email:${targetEmail}:FORGOT_PASSWORD`,
        action: "OTP_HOURLY",
        windowSeconds: 3600,
        maxRequests: 5,
      });
      if (!hourlyCheck.allowed) {
        await client.query("ROLLBACK");
        return res.status(429).json({
          success: false,
          message: "Too many verification codes requested. Please try again later.",
          remainingSeconds: hourlyCheck.remainingSeconds,
        });
      }

      const { rows } = await client.query(
        `SELECT user_id, name, email, role, verification_status
         FROM users
         WHERE LOWER(BTRIM(email)) = LOWER(BTRIM($1))
         FOR UPDATE`,
        [targetEmail]
      );

      if (rows.length > 0) {
        const candidate = rows[0];
        const isRejected =
          (candidate.role === "seller" || candidate.role === "rider") &&
          String(candidate.verification_status || "").toUpperCase() === "REJECTED";

        if (!isRejected) {
          targetUser = candidate;

          // Invalidate previous active FORGOT_PASSWORD OTPs
          await client.query(
            `UPDATE email_otps
             SET used_at = CURRENT_TIMESTAMP
             WHERE user_id = $1 AND purpose = 'FORGOT_PASSWORD' AND used_at IS NULL`,
            [targetUser.user_id]
          );

          otpCode = generateOtp();
          const salt = crypto.randomBytes(16).toString("hex");
          const otpHash = hashOtp(otpCode, salt, targetUser.user_id, "FORGOT_PASSWORD");
          const expiresAt = new Date(Date.now() + 5 * 60 * 1000);

          const { rows: inserted } = await client.query(
            `INSERT INTO email_otps
             (user_id, email, otp_hash, salt, purpose, expires_at, attempts, max_attempts)
             VALUES ($1, $2, $3, $4, 'FORGOT_PASSWORD', $5, 0, 5)
             RETURNING otp_id`,
            [targetUser.user_id, targetUser.email, otpHash, salt, expiresAt]
          );
          createdOtpId = inserted[0].otp_id;
        }
      }

      await client.query("COMMIT");
    } catch (txErr) {
      try {
        await client.query("ROLLBACK");
      } catch (_) {}
      throw txErr;
    } finally {
      client.release();
    }

    if (targetUser && otpCode) {
      const mailRes = await sendOtpEmail({
        to: targetUser.email,
        name: targetUser.name,
        otp: otpCode,
        purpose: "FORGOT_PASSWORD",
      });

      if (!mailRes?.sent) {
        // Invalidate undelivered OTP and release only the 60s cooldown record;
        // still return the identical genericResponse to prevent account enumeration.
        await cleanupFailedOtpDelivery({ otpId: createdOtpId, cooldownRateId });
        console.error(
          "[OTP] FORGOT_PASSWORD email delivery failed:",
          mailRes?.error || "SMTP_ERROR"
        );
        return res.json(genericResponse);
      }

      try {
        await rawPool.query(
          `INSERT INTO audit_logs
           (actor_id, actor_name, actor_role, category, action, target, detail)
           VALUES ($1, $2, $3, 'Auth', 'Requested OTP code', $4, $5)`,
          [
            targetUser.user_id,
            targetUser.name,
            targetUser.role,
            targetUser.email,
            "Generated OTP for FORGOT_PASSWORD.",
          ]
        );
      } catch {
        /* non-fatal */
      }
    }

    return res.json(genericResponse);
  } catch (error) {
    console.error("requestOtp error:", error.code || error.message);
    return res.status(500).json({
      success: false,
      message: "Failed to process OTP request. Please try again.",
    });
  }
}

/**
 * POST /api/auth/otp/verify
 * Verify the 6-digit OTP code with row locking, attempt limiting, and HMAC-SHA-256 comparison
 */
async function verifyOtp(req, res) {
  try {
    await ensureOtpSchema();

    try {
      getOtpHmacSecret();
      getJwtSecret();
    } catch (cfgErr) {
      console.error("[OTP Config Error]", cfgErr.code || cfgErr.message);
      return res.status(500).json({
        success: false,
        message: "OTP verification service is not configured on the server.",
      });
    }

    const { email, otp, purpose = "FORGOT_PASSWORD", firstLoginToken } = req.body || {};

    const cleanOtp = String(otp || "").trim();
    const cleanPurpose = String(purpose || "").trim().toUpperCase();

    if (!ALLOWED_OTP_PURPOSES.has(cleanPurpose)) {
      return res.status(400).json({
        success: false,
        message: "Invalid OTP verification purpose.",
      });
    }

    if (!cleanOtp || cleanOtp.length !== 6 || !/^\d{6}$/.test(cleanOtp)) {
      return res.status(400).json({
        success: false,
        message: "Please enter a valid 6-digit verification code.",
      });
    }

    // Server-side IP rate limit on verification attempts (20 req / 15 min)
    const ipLimit = await checkIpRateLimit(req, "OTP_VERIFY", 900, 20);
    if (!ipLimit.allowed) {
      return res.status(429).json({
        success: false,
        message: `Too many verification attempts. Please wait ${ipLimit.remainingSeconds} second${ipLimit.remainingSeconds === 1 ? "" : "s"} and try again.`,
        remainingSeconds: ipLimit.remainingSeconds,
      });
    }

    let targetEmail = "";
    let userId = null;

    if (cleanPurpose === "FIRST_LOGIN") {
      if (!firstLoginToken) {
        return res.status(401).json({
          success: false,
          message: "First-login token is required.",
        });
      }
      try {
        const decoded = jwt.verify(firstLoginToken, getJwtSecret());
        if (
          decoded.token_type !== "first_login" ||
          decoded.purpose !== "FIRST_LOGIN" ||
          !decoded.user_id
        ) {
          return res.status(401).json({
            success: false,
            message: "Invalid first-login token.",
          });
        }
        userId = decoded.user_id;
        targetEmail = decoded.email;
      } catch {
        return res.status(401).json({
          success: false,
          message: "First-login session expired or invalid. Please sign in again.",
        });
      }
    } else {
      if (!email || typeof email !== "string" || !email.trim()) {
        return res.status(400).json({
          success: false,
          message: "Email is required.",
        });
      }
      targetEmail = email.trim().toLowerCase();
    }

    const client = await rawPool.connect();
    let verifiedRecord = null;

    try {
      await client.query("BEGIN");

      let query = `
        SELECT o.otp_id, o.user_id, o.email, o.otp_hash, o.salt, o.purpose,
               o.expires_at, o.attempts, o.max_attempts, o.verified_at, o.used_at
        FROM email_otps o
        WHERE o.purpose = $1
          AND o.used_at IS NULL
          AND o.verified_at IS NULL
      `;
      const params = [cleanPurpose];

      if (userId) {
        query += ` AND o.user_id = $2 `;
        params.push(userId);
      } else {
        query += ` AND LOWER(BTRIM(o.email)) = LOWER(BTRIM($2)) `;
        params.push(targetEmail);
      }

      query += ` ORDER BY o.created_at DESC LIMIT 1 FOR UPDATE OF o`;

      const { rows } = await client.query(query, params);

      if (!rows.length) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "No active verification code found. Please request a new code.",
        });
      }

      const record = rows[0];

      // Check maximum attempts lockout (max 5)
      if (record.attempts >= record.max_attempts) {
        await client.query("ROLLBACK");
        return res.status(429).json({
          success: false,
          locked: true,
          remainingAttempts: 0,
          message: "Too many failed attempts. This code has been locked. Please request a new code.",
        });
      }

      // Check expiration (5 minutes)
      if (new Date(record.expires_at).getTime() < Date.now()) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          expired: true,
          message: "Verification code has expired. Please request a new code.",
        });
      }

      // Atomically increment attempt count inside transaction
      const { rows: incRows } = await client.query(
        "UPDATE email_otps SET attempts = attempts + 1 WHERE otp_id = $1 RETURNING attempts",
        [record.otp_id]
      );
      const updatedAttempts = incRows[0]?.attempts ?? record.attempts + 1;

      const isValid = verifyOtpHash(
        cleanOtp,
        record.salt,
        record.user_id,
        cleanPurpose,
        record.otp_hash
      );

      if (!isValid) {
        // Persist the incremented attempt count
        await client.query("COMMIT");
        const remainingAttempts = Math.max(0, record.max_attempts - updatedAttempts);
        if (remainingAttempts === 0) {
          return res.status(429).json({
            success: false,
            locked: true,
            remainingAttempts: 0,
            message: "Too many failed attempts. This code has been locked. Please request a new code.",
          });
        }
        return res.status(400).json({
          success: false,
          message: `Invalid verification code. You have ${remainingAttempts} attempt${remainingAttempts === 1 ? "" : "s"} remaining.`,
          remainingAttempts,
        });
      }

      // Mark verified atomically so this OTP cannot be verified a second time
      const { rows: marked } = await client.query(
        `UPDATE email_otps
         SET verified_at = CURRENT_TIMESTAMP
         WHERE otp_id = $1 AND verified_at IS NULL AND used_at IS NULL
         RETURNING otp_id, user_id, email, purpose`,
        [record.otp_id]
      );

      if (!marked.length) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "This verification code has already been used. Please request a new code.",
        });
      }

      verifiedRecord = marked[0];
      await client.query("COMMIT");
    } catch (txErr) {
      try {
        await client.query("ROLLBACK");
      } catch (_) {}
      throw txErr;
    } finally {
      client.release();
    }

    // Issue temporary purpose-bound reset authorization token (10 minutes)
    const resetAuthToken = jwt.sign(
      {
        token_type: "otp_reset",
        otp_id: verifiedRecord.otp_id,
        user_id: verifiedRecord.user_id,
        email: verifiedRecord.email,
        purpose: verifiedRecord.purpose,
      },
      getJwtSecret(),
      { expiresIn: "10m" }
    );

    return res.json({
      success: true,
      message: "Verification successful.",
      resetAuthToken,
    });
  } catch (error) {
    console.error("verifyOtp error:", error.code || error.message);
    return res.status(500).json({
      success: false,
      message: "Failed to verify OTP code. Please try again.",
    });
  }
}

/**
 * POST /api/auth/reset-password-otp
 * Set new password using a verified FORGOT_PASSWORD resetAuthToken
 */
async function resetPasswordWithOtp(req, res) {
  try {
    await ensureOtpSchema();

    try {
      getJwtSecret();
    } catch (cfgErr) {
      console.error("[Auth Config Error]", cfgErr.code || cfgErr.message);
      return res.status(500).json({
        success: false,
        message: "Server authentication configuration error.",
      });
    }

    const { resetAuthToken, newPassword, confirmPassword } = req.body || {};

    if (!resetAuthToken) {
      return res.status(401).json({
        success: false,
        message: "Verification authorization token is required.",
      });
    }

    let decoded;
    try {
      decoded = jwt.verify(resetAuthToken, getJwtSecret());
    } catch {
      return res.status(401).json({
        success: false,
        message: "Your verification session has expired. Please request a new code.",
      });
    }

    if (
      decoded.token_type !== "otp_reset" ||
      decoded.purpose !== "FORGOT_PASSWORD" ||
      !decoded.otp_id ||
      !decoded.user_id
    ) {
      return res.status(401).json({
        success: false,
        message: "Invalid authorization token.",
      });
    }

    if (typeof newPassword !== "string" || newPassword.length < 8) {
      return res.status(400).json({
        success: false,
        message: "Password must be at least 8 characters long.",
      });
    }

    if (newPassword.length > 72) {
      return res.status(400).json({
        success: false,
        message: "Password must not exceed 72 characters.",
      });
    }

    if (newPassword !== confirmPassword) {
      return res.status(400).json({
        success: false,
        message: "Passwords do not match.",
      });
    }

    const client = await rawPool.connect();
    let updatedUser = null;

    try {
      await client.query("BEGIN");

      // Lock OTP row to prevent concurrent reset consumption
      const { rows: otps } = await client.query(
        `SELECT otp_id, user_id, purpose, verified_at, used_at
         FROM email_otps
         WHERE otp_id = $1 AND user_id = $2
         FOR UPDATE`,
        [decoded.otp_id, decoded.user_id]
      );

      if (
        !otps.length ||
        otps[0].purpose !== "FORGOT_PASSWORD" ||
        !otps[0].verified_at ||
        otps[0].used_at
      ) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "This verification code has already been used or is invalid.",
        });
      }

      const { rows: uRows } = await client.query(
        `SELECT user_id, name, email, role, verification_status, password_hash
         FROM users
         WHERE user_id = $1
         FOR UPDATE`,
        [decoded.user_id]
      );

      if (!uRows.length) {
        await client.query("ROLLBACK");
        return res.status(404).json({
          success: false,
          message: "Account not found.",
        });
      }

      const user = uRows[0];

      if (String(user.verification_status || "").toUpperCase() === "REJECTED") {
        await client.query("ROLLBACK");
        return res.status(403).json({
          success: false,
          message: "Your account is inactive or disabled. Please contact the Coordinator.",
        });
      }

      const isSame = await bcrypt.compare(newPassword, user.password_hash);
      if (isSame) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "The new password must be different from your current password.",
        });
      }

      const newHash = await bcrypt.hash(newPassword, 10);

      // Atomically consume OTP
      const { rows: consumed } = await client.query(
        `UPDATE email_otps
         SET used_at = CURRENT_TIMESTAMP
         WHERE otp_id = $1 AND used_at IS NULL
         RETURNING otp_id`,
        [decoded.otp_id]
      );

      if (!consumed.length) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "This verification code has already been used.",
        });
      }

      await client.query(
        `UPDATE users
         SET password_hash = $1, first_login = FALSE, updated_at = CURRENT_TIMESTAMP
         WHERE user_id = $2`,
        [newHash, user.user_id]
      );

      await client.query("COMMIT");
      updatedUser = user;
    } catch (txErr) {
      try {
        await client.query("ROLLBACK");
      } catch (_) {}
      throw txErr;
    } finally {
      client.release();
    }

    try {
      await rawPool.query(
        `INSERT INTO audit_logs
         (actor_id, actor_name, actor_role, category, action, target, detail)
         VALUES ($1, $2, $3, 'Auth', 'Password Reset via OTP', $4, $5)`,
        [
          updatedUser.user_id,
          updatedUser.name,
          updatedUser.role,
          updatedUser.email,
          "Password successfully updated via FORGOT_PASSWORD OTP.",
        ]
      );
    } catch {
      /* non-fatal */
    }

    return res.json({
      success: true,
      message: "Your password has been successfully updated. You can now sign in with your new password.",
    });
  } catch (error) {
    console.error("resetPasswordWithOtp error:", error.code || error.message);
    return res.status(500).json({
      success: false,
      message: "Failed to reset password. Please try again.",
    });
  }
}

/**
 * POST /api/auth/first-login-change-password
 * Concurrency-safe first-time login OTP verification & password setup
 */
async function firstLoginChangePassword(req, res) {
  try {
    await ensurePolicySchema();
    await ensureOtpSchema();

    try {
      getOtpHmacSecret();
      getJwtSecret();
    } catch (cfgErr) {
      console.error("[OTP Config Error]", cfgErr.code || cfgErr.message);
      return res.status(500).json({
        success: false,
        message: "OTP verification service is not configured on the server.",
      });
    }

    const { firstLoginToken, otp, newPassword, confirmPassword, policyVersion } = req.body || {};

    if (!firstLoginToken) {
      return res.status(401).json({
        success: false,
        message: "First-login session token is required.",
      });
    }

    let decoded;
    try {
      decoded = jwt.verify(firstLoginToken, getJwtSecret());
    } catch {
      return res.status(401).json({
        success: false,
        message: "First-login session expired. Please sign in again.",
      });
    }

    if (
      decoded.token_type !== "first_login" ||
      decoded.purpose !== "FIRST_LOGIN" ||
      !decoded.user_id
    ) {
      return res.status(401).json({
        success: false,
        message: "Invalid first-login session.",
      });
    }

    const cleanOtp = String(otp || "").trim();
    if (!cleanOtp || cleanOtp.length !== 6 || !/^\d{6}$/.test(cleanOtp)) {
      return res.status(400).json({
        success: false,
        message: "Please enter a valid 6-digit OTP code.",
      });
    }

    if (typeof newPassword !== "string" || newPassword.length < 8) {
      return res.status(400).json({
        success: false,
        message: "Password must be at least 8 characters long.",
      });
    }

    if (newPassword.length > 72) {
      return res.status(400).json({
        success: false,
        message: "Password must not exceed 72 characters.",
      });
    }

    if (newPassword !== confirmPassword) {
      return res.status(400).json({
        success: false,
        message: "Passwords do not match.",
      });
    }

    // Server-side IP rate limit shared with /otp/verify (20 req / 15 min)
    const ipLimit = await checkIpRateLimit(req, "OTP_VERIFY", 900, 20);
    if (!ipLimit.allowed) {
      return res.status(429).json({
        success: false,
        message: `Too many verification attempts. Please wait ${ipLimit.remainingSeconds} second${ipLimit.remainingSeconds === 1 ? "" : "s"} and try again.`,
        remainingSeconds: ipLimit.remainingSeconds,
      });
    }

    const appliedVersion =
      typeof policyVersion === "string" && policyVersion.trim()
        ? policyVersion.trim().slice(0, 50)
        : CURRENT_POLICY_VERSION;

    const client = await rawPool.connect();
    let safeUser = null;
    let home = "/dashboard";
    let sessionVersion = 1;

    try {
      await client.query("BEGIN");

      // Lock user row and validate eligibility
      const { rows: uRows } = await client.query(
        `SELECT user_id, name, email, phone, avatar, role, verification_status,
                first_login, password_hash, rider_type, rider_code, agency,
                is_deleted, session_version
         FROM users
         WHERE user_id = $1
         FOR UPDATE`,
        [decoded.user_id]
      );

      if (!uRows.length || Boolean(uRows[0].is_deleted)) {
        await client.query("ROLLBACK");
        return res.status(404).json({
          success: false,
          message: "User account not found.",
        });
      }

      const user = uRows[0];
      const actualRole = String(user.role || "").trim().toLowerCase();
      const verificationStatus = String(user.verification_status || "").toUpperCase();

      if (!["seller", "rider", "coordinator"].includes(actualRole)) {
        await client.query("ROLLBACK");
        return res.status(403).json({
          success: false,
          message: "Your account does not have an authorized role. Please contact support.",
        });
      }

      if (verificationStatus === "REJECTED") {
        await client.query("ROLLBACK");
        return res.status(403).json({
          success: false,
          message: "Your account is inactive or disabled. Please contact the Coordinator.",
        });
      }

      if (verificationStatus === "PENDING" && (actualRole === "seller" || actualRole === "rider")) {
        await client.query("ROLLBACK");
        return res.status(403).json({
          success: false,
          message: "Your account is pending Coordinator approval.",
        });
      }

      if (!Boolean(user.first_login)) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "First-time password setup has already been completed for this account.",
        });
      }

      // Lock latest active FIRST_LOGIN OTP
      const { rows: otpRows } = await client.query(
        `SELECT otp_id, user_id, otp_hash, salt, expires_at, attempts, max_attempts, verified_at, used_at
         FROM email_otps
         WHERE user_id = $1
           AND purpose = 'FIRST_LOGIN'
           AND used_at IS NULL
           AND verified_at IS NULL
         ORDER BY created_at DESC
         LIMIT 1
         FOR UPDATE`,
        [user.user_id]
      );

      if (!otpRows.length) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "No active verification code found. Please request a new code.",
        });
      }

      const record = otpRows[0];

      if (record.attempts >= record.max_attempts) {
        await client.query("ROLLBACK");
        return res.status(429).json({
          success: false,
          locked: true,
          remainingAttempts: 0,
          message: "Too many failed attempts. This code has been locked. Please request a new code.",
        });
      }

      if (new Date(record.expires_at).getTime() < Date.now()) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          expired: true,
          message: "Verification code has expired. Please request a new code.",
        });
      }

      // Increment attempt count inside transaction
      const { rows: incRows } = await client.query(
        "UPDATE email_otps SET attempts = attempts + 1 WHERE otp_id = $1 RETURNING attempts",
        [record.otp_id]
      );
      const updatedAttempts = incRows[0]?.attempts ?? record.attempts + 1;

      const isValid = verifyOtpHash(
        cleanOtp,
        record.salt,
        user.user_id,
        "FIRST_LOGIN",
        record.otp_hash
      );

      if (!isValid) {
        await client.query("COMMIT");
        const remainingAttempts = Math.max(0, record.max_attempts - updatedAttempts);
        if (remainingAttempts === 0) {
          return res.status(429).json({
            success: false,
            locked: true,
            remainingAttempts: 0,
            message: "Too many failed attempts. This code has been locked. Please request a new code.",
          });
        }
        return res.status(400).json({
          success: false,
          message: `Invalid verification code. You have ${remainingAttempts} attempt${remainingAttempts === 1 ? "" : "s"} remaining.`,
          remainingAttempts,
        });
      }

      const isSame = await bcrypt.compare(newPassword, user.password_hash);
      if (isSame) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "The new password must be different from your temporary password.",
        });
      }

      const newHash = await bcrypt.hash(newPassword, 10);

      // Atomically consume OTP
      const { rows: consumed } = await client.query(
        `UPDATE email_otps
         SET verified_at = CURRENT_TIMESTAMP, used_at = CURRENT_TIMESTAMP
         WHERE otp_id = $1 AND used_at IS NULL
         RETURNING otp_id`,
        [record.otp_id]
      );

      if (!consumed.length) {
        await client.query("ROLLBACK");
        return res.status(400).json({
          success: false,
          message: "This verification code has already been used.",
        });
      }

      // Update password, clear first_login, and record policy acceptance
      const { rows: updatedRows } = await client.query(
        `UPDATE users
         SET password_hash = $1,
             first_login = FALSE,
             terms_accepted = TRUE,
             privacy_accepted = TRUE,
             policy_version = $2,
             terms_accepted_at = CURRENT_TIMESTAMP,
             updated_at = CURRENT_TIMESTAMP
         WHERE user_id = $3
         RETURNING terms_accepted_at`,
        [newHash, appliedVersion, user.user_id]
      );

      const acceptedAt =
        updatedRows?.[0]?.terms_accepted_at || new Date().toISOString();

      await client.query(
        `INSERT INTO user_policy_acceptances
         (user_id, user_role, terms_accepted, privacy_accepted, policy_version, accepted_at)
         VALUES ($1, $2, TRUE, TRUE, $3, CURRENT_TIMESTAMP)`,
        [user.user_id, actualRole, appliedVersion]
      );

      await client.query("COMMIT");

      const riderInfo =
        actualRole === "rider"
          ? {
              rider_type: user.rider_type || "LM",
              rider_code: user.rider_code || null,
              agency: user.agency || null,
            }
          : {};

      home = actualRole === "seller" ? "/seller" : actualRole === "rider" ? "/rider" : "/dashboard";
      sessionVersion = Number(user.session_version || 1);

      safeUser = {
        user_id: user.user_id,
        name: user.name,
        email: user.email,
        phone: user.phone || null,
        avatar: user.avatar || null,
        role: actualRole,
        ...riderInfo,
        terms_accepted: true,
        privacy_accepted: true,
        policy_version: appliedVersion,
        terms_accepted_at: acceptedAt,
      };
    } catch (txErr) {
      try {
        await client.query("ROLLBACK");
      } catch (_) {}
      throw txErr;
    } finally {
      client.release();
    }

    try {
      await rawPool.query(
        `INSERT INTO audit_logs
         (actor_id, actor_name, actor_role, category, action, target, detail)
         VALUES ($1, $2, $3, 'Auth', 'Completed first-login password setup', $4, $5)`,
        [
          safeUser.user_id,
          safeUser.name,
          safeUser.role,
          safeUser.email,
          `Completed OTP-verified first-time password change and accepted Terms & Privacy Policy (${appliedVersion}).`,
        ]
      );
    } catch {
      /* non-fatal */
    }

    const token = createToken({
      ...safeUser,
      session_version: sessionVersion,
    });

    return res.json({
      success: true,
      message: "Password successfully configured! Welcome to LogiSync.",
      token,
      user: safeUser,
      redirectUrl: home,
    });
  } catch (error) {
    console.error("firstLoginChangePassword error:", error.code || error.message);
    return res.status(500).json({
      success: false,
      message: "Failed to update password for first-time login.",
    });
  }
}

