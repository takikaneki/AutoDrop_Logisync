const bcrypt = require("bcryptjs");
const jwt = require("jsonwebtoken");
const { pool, rawPool } = require("../config/database");

const CURRENT_POLICY_VERSION = "2026.1";
let policySchemaReady = false;

async function ensurePolicySchema() {
  if (policySchemaReady) return;
  await rawPool.query(`
    ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS privacy_accepted BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE users ADD COLUMN IF NOT EXISTS policy_version VARCHAR(50);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMPTZ;

    CREATE TABLE IF NOT EXISTS user_policy_acceptances (
      acceptance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
      user_role VARCHAR(20) NOT NULL,
      terms_accepted BOOLEAN NOT NULL DEFAULT TRUE,
      privacy_accepted BOOLEAN NOT NULL DEFAULT TRUE,
      policy_version VARCHAR(50) NOT NULL,
      accepted_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_policy_acceptances_user ON user_policy_acceptances(user_id);
  `);
  policySchemaReady = true;
}

function createToken(user) {
  return jwt.sign(
    {
      user_id: user.user_id,
      name: user.name,
      email: user.email,
      role: user.role,
      policy_version: user.policy_version || CURRENT_POLICY_VERSION,
      terms_accepted: Boolean(user.terms_accepted),
    },
    process.env.JWT_SECRET,
    { expiresIn: "8h" }
  );
}

async function register(req, res) {
  try {
    await ensurePolicySchema();
    const { name, email, password, termsAccepted, policyVersion } = req.body;

    if (
      typeof name !== "string" ||
      !name.trim() ||
      typeof email !== "string" ||
      !email.trim() ||
      typeof password !== "string" ||
      !password
    ) {
      return res.status(400).json({
        success: false,
        message: "Name, email, and password are required.",
      });
    }

    if (password.length < 6) {
      return res.status(400).json({
        success: false,
        message: "Password must be at least 6 characters.",
      });
    }

    const cleanName = name.trim();
    const cleanEmail = email.trim().toLowerCase();

    const [existing] = await pool.query(
      "SELECT user_id FROM users WHERE email = ?",
      [cleanEmail]
    );

    if (existing.length > 0) {
      return res.status(409).json({
        success: false,
        message: "Email is already registered.",
      });
    }

    const passwordHash = await bcrypt.hash(password, 10);
    const role = "seller";
    const accepted = Boolean(termsAccepted);
    const appliedVersion =
      typeof policyVersion === "string" && policyVersion.trim()
        ? policyVersion.trim().slice(0, 50)
        : CURRENT_POLICY_VERSION;

    const [result] = await pool.query(
      `INSERT INTO users
       (name, email, password_hash, role, verification_status, terms_accepted, privacy_accepted, policy_version, terms_accepted_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, CASE WHEN ? THEN CURRENT_TIMESTAMP ELSE NULL END)`,
      [
        cleanName,
        cleanEmail,
        passwordHash,
        role,
        "PENDING",
        accepted,
        accepted,
        accepted ? appliedVersion : null,
        accepted,
      ]
    );

    if (accepted && result.insertId) {
      await pool.query(
        `INSERT INTO user_policy_acceptances
         (user_id, user_role, terms_accepted, privacy_accepted, policy_version)
         VALUES (?, ?, TRUE, TRUE, ?)`,
        [result.insertId, role, appliedVersion]
      );
    }

    const user = {
      user_id: result.insertId,
      name: cleanName,
      email: cleanEmail,
      role,
    };

    return res.status(201).json({
      success: true,
      message: "Registration successful. Your account is pending Coordinator approval.",
      user: {
        user_id: user.user_id,
        name: user.name,
        email: user.email,
        role: user.role,
        verification_status: "PENDING",
        terms_accepted: accepted,
        privacy_accepted: accepted,
        policy_version: accepted ? appliedVersion : null,
      },
    });
  } catch (error) {
    console.error("Registration error:", error);

    return res.status(500).json({
      success: false,
      message: "Registration failed.",
    });
  }
}

async function login(req, res) {
  try {
    await ensurePolicySchema();
    const { email, password, termsAccepted, policyVersion } = req.body;

    if (!email || !password) {
      return res
        .status(400)
        .json({ success: false, message: "Email and password are required." });
    }

    if (!termsAccepted) {
      return res.status(400).json({
        success: false,
        message:
          "You must agree to the Terms and Conditions and Privacy Policy before signing in.",
      });
    }

    const [rows] = await pool.query(
      `SELECT user_id, name, email, password_hash, role, verification_status
       FROM users
       WHERE email = ?`,
      [email.trim().toLowerCase()]
    );

    if (!rows.length) {
      return res
        .status(401)
        .json({ success: false, message: "Invalid email or password." });
    }

    const user = rows[0];
    const valid = await bcrypt.compare(password, user.password_hash);

    if (!valid) {
      return res
        .status(401)
        .json({ success: false, message: "Invalid email or password." });
    }

    if (
      (user.role === "seller" || user.role === "rider") &&
      String(user.verification_status || "").toUpperCase() === "REJECTED"
    ) {
      return res.status(403).json({
        success: false,
        message:
          "Your account has been suspended. Please contact the Coordinator.",
      });
    }

    const appliedVersion =
      typeof policyVersion === "string" && policyVersion.trim()
        ? policyVersion.trim().slice(0, 50)
        : CURRENT_POLICY_VERSION;

    // Save the user's agreement status, policy version, and acceptance timestamp in the database
    const [updatedRows] = await pool.query(
      `UPDATE users
       SET terms_accepted = TRUE,
           privacy_accepted = TRUE,
           policy_version = ?,
           terms_accepted_at = CURRENT_TIMESTAMP
       WHERE user_id = ?
       RETURNING terms_accepted_at`,
      [appliedVersion, user.user_id]
    );

    const acceptedAt =
      updatedRows?.[0]?.terms_accepted_at || new Date().toISOString();

    await pool.query(
      `INSERT INTO user_policy_acceptances
       (user_id, user_role, terms_accepted, privacy_accepted, policy_version, accepted_at)
       VALUES (?, ?, TRUE, TRUE, ?, CURRENT_TIMESTAMP)`,
      [user.user_id, user.role, appliedVersion]
    );

    // Record acceptance in system audit logs for compliance traceability
    try {
      await pool.query(
        `INSERT INTO audit_logs
         (actor_id, actor_name, actor_role, category, action, target, detail)
         VALUES (?, ?, ?, 'Auth', 'Accepted Terms & Privacy Policy', ?, ?)`,
        [
          user.user_id,
          user.name,
          user.role,
          user.email,
          `Accepted Terms and Conditions & Privacy Policy (${appliedVersion}) upon sign-in.`,
        ]
      );
    } catch {
      /* non-fatal if audit_logs insert fails */
    }

    const safeUser = {
      user_id: user.user_id,
      name: user.name,
      email: user.email,
      role: user.role,
      terms_accepted: true,
      privacy_accepted: true,
      policy_version: appliedVersion,
      terms_accepted_at: acceptedAt,
    };

    res.json({
      success: true,
      message: "Login successful.",
      token: createToken(safeUser),
      user: safeUser,
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ success: false, message: "Login failed." });
  }
}

async function me(req, res) {
  try {
    await ensurePolicySchema();
    const [rows] = await pool.query(
      `SELECT user_id, name, email, role, terms_accepted, privacy_accepted, policy_version, terms_accepted_at
       FROM users
       WHERE user_id = ?`,
      [req.user.user_id]
    );
    if (rows.length > 0) {
      return res.json({ success: true, user: rows[0] });
    }
  } catch {
    /* fallback to JWT user */
  }
  res.json({ success: true, user: req.user });
}

async function verifyPassword(req, res) {
  try {
    const currentPassword = req.body?.currentPassword ?? req.body?.password;
    if (typeof currentPassword !== "string" || !currentPassword) {
      return res.status(400).json({
        success: false,
        message: "Please enter your current password.",
      });
    }

    const userId = Number(req.user?.user_id);
    if (!Number.isInteger(userId) || userId <= 0) {
      return res.status(401).json({
        success: false,
        message: "Authentication required.",
      });
    }

    const [rows] = await pool.query(
      `SELECT user_id, password_hash FROM users WHERE user_id = ?`,
      [userId]
    );

    if (!rows.length) {
      return res.status(404).json({
        success: false,
        message: "Account not found.",
      });
    }

    const valid = await bcrypt.compare(currentPassword, rows[0].password_hash);
    if (!valid) {
      return res.status(400).json({
        success: false,
        message: "Incorrect current password.",
      });
    }

    return res.json({
      success: true,
      message: "Current password verified.",
    });
  } catch (error) {
    console.error("verifyPassword error:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to verify current password.",
    });
  }
}

async function changePassword(req, res) {
  try {
    const { currentPassword, newPassword, confirmPassword } = req.body || {};

    if (typeof currentPassword !== "string" || !currentPassword) {
      return res.status(400).json({
        success: false,
        message: "Please enter your current password.",
      });
    }

    if (typeof newPassword !== "string" || newPassword.length < 8) {
      return res.status(400).json({
        success: false,
        message: "The new password must be at least 8 characters.",
      });
    }

    if (confirmPassword !== undefined && newPassword !== confirmPassword) {
      return res.status(400).json({
        success: false,
        message: "The new passwords do not match.",
      });
    }

    const userId = Number(req.user?.user_id);
    if (!Number.isInteger(userId) || userId <= 0) {
      return res.status(401).json({
        success: false,
        message: "Authentication required.",
      });
    }

    const [rows] = await pool.query(
      `SELECT user_id, name, email, role, password_hash
       FROM users
       WHERE user_id = ?`,
      [userId]
    );

    if (!rows.length) {
      return res.status(404).json({
        success: false,
        message: "Account not found.",
      });
    }

    const user = rows[0];
    const valid = await bcrypt.compare(currentPassword, user.password_hash);
    if (!valid) {
      return res.status(400).json({
        success: false,
        message: "Incorrect current password.",
      });
    }

    const sameAsCurrent =
      newPassword === currentPassword ||
      (await bcrypt.compare(newPassword, user.password_hash));
    if (sameAsCurrent) {
      return res.status(400).json({
        success: false,
        message: "The new password must be different from the current one.",
      });
    }

    const newPasswordHash = await bcrypt.hash(newPassword, 10);

    await pool.query(
      `UPDATE users
       SET password_hash = ?, updated_at = CURRENT_TIMESTAMP
       WHERE user_id = ?`,
      [newPasswordHash, user.user_id]
    );

    try {
      await pool.query(
        `INSERT INTO audit_logs
         (actor_id, actor_name, actor_role, category, action, target, detail)
         VALUES (?, ?, ?, 'Settings', 'Changed password', ?, ?)`,
        [
          user.user_id,
          user.name,
          user.role,
          user.email,
          "User updated their account password.",
        ]
      );
    } catch {
      /* non-fatal if audit_logs insert fails */
    }

    return res.json({
      success: true,
      message: "Password updated successfully.",
    });
  } catch (error) {
    console.error("changePassword error:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to update password.",
    });
  }
}

module.exports = { register, login, me, verifyPassword, changePassword };