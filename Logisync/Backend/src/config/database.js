const { Pool, types } = require("pg");
require("dotenv").config();

// Ensure PostgreSQL INT8 (bigint and COUNT) are returned as numbers instead of strings
types.setTypeParser(20, (val) => parseInt(val, 10));

const connectionString = process.env.DATABASE_URL;
const isNeon =
  (connectionString && connectionString.includes("neon.tech")) ||
  process.env.DB_SSL === "true";

const poolConfig = connectionString
  ? {
      connectionString,
      ssl: isNeon ? { rejectUnauthorized: false } : undefined,
    }
  : {
      host: process.env.DB_HOST || "localhost",
      port: Number(process.env.DB_PORT || 5432),
      user: process.env.DB_USER || "postgres",
      password: process.env.DB_PASSWORD || "",
      database: process.env.DB_NAME || "synclink_db",
      ssl: isNeon ? { rejectUnauthorized: false } : undefined,
    };

const rawPool = new Pool(poolConfig);

/**
 * Converts MySQL-style '?' placeholders to PostgreSQL '$1', '$2', ...
 */
function convertPlaceholders(sql) {
  let paramIndex = 1;
  return sql.replace(/\?/g, () => `$${paramIndex++}`);
}

/**
 * Appends RETURNING * to INSERT queries if not already present,
 * to capture insertId seamlessly.
 */
function normalizeQuery(sql) {
  let text = convertPlaceholders(sql.trim());
  const isInsert = /^\s*INSERT\s+INTO\b/i.test(text);
  if (isInsert && !/\bRETURNING\b/i.test(text)) {
    text = text.replace(/;+\s*$/, "") + " RETURNING *";
  }
  return text;
}

/**
 * Wraps PostgreSQL result into MySQL-compatible [rows, meta] structure
 */
function formatResult(pgResult) {
  const rows = pgResult.rows || [];
  const firstRow = rows[0] || {};
  const insertId =
    firstRow.user_id ??
    firstRow.video_id ??
    firstRow.verification_id ??
    firstRow.message_id ??
    firstRow.log_id ??
    firstRow.parcel_id ??
    null;

  const affectedRows = pgResult.rowCount || 0;
  rows.insertId = insertId;
  rows.affectedRows = affectedRows;
  rows.rowCount = affectedRows;

  const meta = {
    insertId,
    affectedRows,
    rowCount: affectedRows,
    rows,
  };

  return [rows, meta];
}

async function executeQuery(executor, sql, params = []) {
  const text = normalizeQuery(sql);
  const result = await executor.query(text, params);
  return formatResult(result);
}

const pool = {
  query: (sql, params) => executeQuery(rawPool, sql, params),
  getConnection: async () => {
    const client = await rawPool.connect();
    return {
      query: (sql, params) => executeQuery(client, sql, params),
      beginTransaction: async () => client.query("BEGIN"),
      commit: async () => client.query("COMMIT"),
      rollback: async () => {
        try {
          await client.query("ROLLBACK");
        } catch (_) {}
      },
      release: () => client.release(),
    };
  },
  end: () => rawPool.end(),
};

async function ensureSchema() {
  const client = await rawPool.connect();
  try {
    await client.query(`
      CREATE TABLE IF NOT EXISTS users (
        user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(100) NOT NULL,
        email VARCHAR(150) NOT NULL UNIQUE,
        password_hash VARCHAR(255) NOT NULL,
        role VARCHAR(20) NOT NULL CHECK (role IN ('seller', 'coordinator', 'rider')),
        verification_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED' CHECK (verification_status IN ('PENDING', 'APPROVED', 'REJECTED')),
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_status VARCHAR(20) NOT NULL DEFAULT 'APPROVED';

      CREATE TABLE IF NOT EXISTS parcels (
        parcel_id VARCHAR(50) PRIMARY KEY,
        seller_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
        receiver_name VARCHAR(100) NOT NULL,
        receiver_contact VARCHAR(50),
        contents VARCHAR(255),
        transaction_number VARCHAR(100),
        status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
            CHECK (status IN ('PENDING', 'WAITING_FOR_VIDEO', 'VIDEO_SUBMITTED', 'VERIFIED', 'REJECTED', 'REUPLOAD_REQUESTED')),
        verification_status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
            CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED', 'REUPLOAD_REQUESTED')),
        rider_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL ON UPDATE CASCADE,
        delivery_status VARCHAR(20) CHECK (delivery_status IN ('TO_DELIVER', 'DELIVERED', 'FAILED')),
        delivery_note VARCHAR(500),
        scanned_at TIMESTAMPTZ,
        delivered_at TIMESTAMPTZ,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS transaction_number VARCHAR(100);
      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS rider_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL ON UPDATE CASCADE;
      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS delivery_status VARCHAR(20);
      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS delivery_note VARCHAR(500);
      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS scanned_at TIMESTAMPTZ;
      ALTER TABLE parcels ADD COLUMN IF NOT EXISTS delivered_at TIMESTAMPTZ;

      CREATE TABLE IF NOT EXISTS video_proofs (
        video_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parcel_id VARCHAR(50) NOT NULL REFERENCES parcels(parcel_id) ON DELETE CASCADE ON UPDATE CASCADE,
        uploaded_by INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
        file_name VARCHAR(255) NOT NULL,
        file_path VARCHAR(500) NOT NULL,
        file_size BIGINT NOT NULL,
        mime_type VARCHAR(100) NOT NULL,
        uploaded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );
      ALTER TABLE video_proofs
      ADD COLUMN IF NOT EXISTS cloudinary_public_id VARCHAR(255);

      CREATE TABLE IF NOT EXISTS verification_records (
        verification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parcel_id VARCHAR(50) NOT NULL REFERENCES parcels(parcel_id) ON DELETE CASCADE ON UPDATE CASCADE,
        coordinator_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
        decision VARCHAR(30) NOT NULL CHECK (decision IN ('VERIFY', 'REJECT', 'REQUEST_REUPLOAD')),
        remarks TEXT,
        verified_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS communication_messages (
        message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        sender_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
        receiver_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT ON UPDATE CASCADE,
        message TEXT NOT NULL,
        is_read BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS audit_logs (
        log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id INTEGER,
        actor_name VARCHAR(100) NOT NULL,
        actor_role VARCHAR(20) NOT NULL,
        category VARCHAR(40) NOT NULL,
        action VARCHAR(100) NOT NULL,
        target VARCHAR(100),
        detail VARCHAR(500),
        seller_id INTEGER,
        rider_id INTEGER,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      CREATE OR REPLACE FUNCTION update_updated_at()
      RETURNS TRIGGER AS $$
      BEGIN
          NEW.updated_at = CURRENT_TIMESTAMP;
          RETURN NEW;
      END;
      $$ LANGUAGE plpgsql;

      DO $$
      BEGIN
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'users_updated_at_trigger') THEN
          CREATE TRIGGER users_updated_at_trigger
          BEFORE UPDATE ON users
          FOR EACH ROW
          EXECUTE FUNCTION update_updated_at();
        END IF;

        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'parcels_updated_at_trigger') THEN
          CREATE TRIGGER parcels_updated_at_trigger
          BEFORE UPDATE ON parcels
          FOR EACH ROW
          EXECUTE FUNCTION update_updated_at();
        END IF;
      END $$;
    `);
  } finally {
    client.release();
  }
}

async function testConnection() {
  const client = await rawPool.connect();
  try {
    await client.query("SELECT 1");
    await ensureSchema();
  } finally {
    client.release();
  }
}

module.exports = { pool, rawPool, testConnection, ensureSchema };
