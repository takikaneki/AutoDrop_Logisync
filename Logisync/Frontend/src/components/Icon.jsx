const STORED_ALIASES = {
  bullhorn: "megaphone",
  warehouse: "undo-2",
  "triangle-exclamation": "triangle-alert",
  "calendar-day": "calendar-days",
  "rotate-left": "undo-2",
  box: "package",
  ban: "circle-x",
  message: "message-circle",
};

const HAS_HEIGHT_RE = /(?:^|\s)(?:[a-z0-9\[\]_-]+:)?(?:h-|size-)/;
const HAS_WIDTH_RE = /(?:^|\s)(?:[a-z0-9\[\]_-]+:)?(?:w-|size-)/;

const SOLID_FILLED_ICONS = new Set(["star", "circle"]);

export default function Icon({
  name,
  className = "",
  size,
  strokeWidth = 2.2,
  filled = false,
  spin = false,
  ...rest
}) {
  const raw = typeof name === "string" ? name.trim() : "";
  const normalized = raw.replace(/^(?:fa-solid|fa-regular|fa-brands)\s+/, "").replace(/^fa-/, "");
  const key = ICONS[raw] ? raw : STORED_ALIASES[normalized] || normalized;
  const Component = ICONS[key] || Circle;

  const hasHeight = HAS_HEIGHT_RE.test(className);
  const hasWidth = HAS_WIDTH_RE.test(className);
  const autoSize =
    size !== undefined
      ? ""
      : hasHeight && hasWidth
        ? ""
        : hasHeight
          ? "w-auto"
          : hasWidth
            ? "h-[1.08em]"
            : "h-[1.08em] w-[1.08em]";

  const classes = [
    "inline-block shrink-0 align-[-0.14em]",
    autoSize,
    spin ? "animate-spin" : "",
    className,
  ]
    .filter(Boolean)
    .join(" ");

  const resolvedStrokeWidth = filled ? Math.max(Number(strokeWidth) || 2.2, 2.35) : strokeWidth;
  const fillProps = filled
    ? SOLID_FILLED_ICONS.has(key)
      ? { fill: "currentColor" }
      : { fill: "currentColor", fillOpacity: 0.22 }
    : {};

  return (
    <Component
      size={size}
      strokeWidth={resolvedStrokeWidth}
      aria-hidden={rest["aria-label"] ? undefined : "true"}
      className={classes}
      {...fillProps}
      {...rest}
    />
  );
}
