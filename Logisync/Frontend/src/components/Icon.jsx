const STORED_ALIASES = {
  bullhorn: "megaphone",
  "triangle-exclamation": "triangle-alert",
  "calendar-day": "calendar-days",
  "rotate-left": "undo-2",
  box: "package",
  ban: "circle-x",
  message: "message-circle",
};

const HAS_HEIGHT_RE = /(?:^|\s)(?:[a-z0-9\[\]_-]+:)?(?:h-|size-)/;
const HAS_WIDTH_RE = /(?:^|\s)(?:[a-z0-9\[\]_-]+:)?(?:w-|size-)/;

export default function Icon({
  name,
  className = "",
  size,
  weight,
  filled: _filled,
  strokeWidth: _strokeWidth,
  spin = false,
  ...rest
}) {
  const raw = typeof name === "string" ? name.trim() : "";
  const normalized = raw.replace(/^(?:fa-solid|fa-regular|fa-brands)\s+/, "").replace(/^fa-/, "");
  const key = ICONS[raw] ? raw : STORED_ALIASES[normalized] || normalized;
  const Component = ICONS[key] || Circle;

  const hasHeight = HAS_HEIGHT_RE.test(className);
  const hasWidth = HAS_WIDTH_RE.test(className);
  const autoSize =
    size !== undefined
      ? ""
      : hasHeight && hasWidth
        ? ""
        : hasHeight
          ? "w-auto"
          : hasWidth
            ? "h-[1.12em]"
            : "h-[1.12em] w-[1.12em]";

  const classes = [
    "inline-block shrink-0 align-[-0.15em]",
    autoSize,
    spin ? "animate-spin" : "",
    className,
  ]
    .filter(Boolean)
    .join(" ");

  const resolvedWeight = weight || (BOLD_STROKE_ICONS.has(key) ? "bold" : "fill");

  return (
    <Component
      size={size}
      weight={resolvedWeight}
      aria-hidden={rest["aria-label"] ? undefined : "true"}
      className={classes}
      {...rest}
    />
  );
}
