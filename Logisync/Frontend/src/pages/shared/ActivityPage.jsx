import Topbar from "../../components/Topbar.jsx";
import AuditTable from "../../components/audit/AuditTable.jsx";
import { getRole } from "../../api.js";

// Personal Activity Log ng Seller at Rider: sariling account actions lang ang makikita.
export default function ActivityPage() {
  const role = getRole();
  const note =
    role === "seller"
      ? "You only see activity logs generated by your own Seller account."
      : "You only see activity logs generated by your own Rider account.";
  return (
    <>
      <Topbar title="Activity Log" subtitle="A personal record of activities performed by your account." />
      <AuditTable note={note} />
    </>
  );
}
